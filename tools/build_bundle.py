#!/usr/bin/env python3
"""Bundle modules/*.md into js/modules-bundle.js so the course works from file://
(browsers block fetch() of local files). Re-run after editing any module.

Also validates each module: lesson word count (< 800), quiz JSON (3-5 questions),
and the required sections.

Usage: python3 tools/build_bundle.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODULES = ROOT / "modules"
OUT = ROOT / "js" / "modules-bundle.js"
REQUIRED = ["## Lesson", "## Worked example", "## What would break this trade", "## Quiz"]


def lesson_words(text):
    m = re.search(r"^## Lesson\s*$(.*?)^## ", text, re.S | re.M)
    if not m:
        return None
    body = re.sub(r"```.*?```", " ", m.group(1), flags=re.S)
    body = re.sub(r"\[\[\w+\]\]", " ", body)
    body = re.sub(r"\]\([^)]*\)", "]", body)
    body = re.sub(r"<https?://[^>]+>", " ", body)
    return len(re.findall(r"[A-Za-z0-9$%][\w$%.,'’/-]*", body))


def check(name, text):
    problems = []
    for sec in REQUIRED:
        if sec not in text:
            problems.append("missing section " + sec)
    if "not personalized financial advice" not in text:
        problems.append("missing disclaimer")
    words = lesson_words(text)
    if words is None or words >= 800:
        problems.append("lesson word count %s (must be < 800)" % words)
    quizzes = re.findall(r"```quiz\s*\n(.*?)\n```", text, re.S)
    if len(quizzes) != 1:
        problems.append("expected exactly one quiz block, found %d" % len(quizzes))
    for q in quizzes:
        try:
            data = json.loads(q)
        except json.JSONDecodeError as e:
            problems.append("quiz JSON error: %s" % e)
            continue
        if not 3 <= len(data) <= 5:
            problems.append("quiz has %d questions (need 3-5)" % len(data))
        for i, item in enumerate(data):
            if not (0 <= item.get("answer", -1) < len(item.get("options", []))):
                problems.append("quiz q%d answer index out of range" % (i + 1))
            if not item.get("explain"):
                problems.append("quiz q%d missing explanation" % (i + 1))
    for p in re.findall(r"```payoff\s*\n(.*?)\n```", text, re.S):
        try:
            json.loads(p)
        except json.JSONDecodeError as e:
            problems.append("payoff JSON error: %s" % e)
    return words, problems


def main():
    bundle = {}
    failed = False
    for path in sorted(MODULES.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        words, problems = check(path.name, text)
        status = "OK" if not problems else "FAIL: " + "; ".join(problems)
        print("%-34s lesson words=%-4s %s" % (path.name, words, status))
        failed = failed or bool(problems)
        bundle[path.name] = text
    js = ("/* GENERATED by tools/build_bundle.py from modules/*.md — do not edit by hand. */\n"
          "window.MODULE_SOURCES = " + json.dumps(bundle, ensure_ascii=False, indent=1) + ";\n")
    OUT.write_text(js, encoding="utf-8")
    print("Wrote %s (%d modules)" % (OUT.relative_to(ROOT), len(bundle)))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
